/** FinderPlan query banks — 3 lists, perRound=5, product+city weaves (source_finder.dart). */
function weave(a, b) {
  const out = [];
  const n = Math.max(a.length, b.length);
  for (let i = 0; i < n; i++) {
    if (i < a.length) out.push(a[i]);
    if (i < b.length) out.push(b[i]);
  }
  return out;
}

